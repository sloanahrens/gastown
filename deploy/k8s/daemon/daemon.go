// Package daemon renders the Kubernetes objects the town's daemon needs on the
// control cluster: the namespace, the ServiceAccount the pod runs as, the
// claims that carry the town root, the landing work root and the host's Dolt
// backups, the Service that keeps the name forgejo, one Secret per file of the
// daemon's secrets manifest, the Deployment itself, the seed helper Pod
// BuildHelper returns, and the bindings that give the pod the sweep roles
// deploy/k8s/sweep-rbac.yaml defines. It renders only, so no apply path and no
// Kubernetes client lives here (gt-gg9hv.69, gt-gg9hv.70, gt-p194yr).
//
// The pod mounts each volume at the path the compose container mounts it at, so
// no setting that names a path changes at the move (gt-gg9hv.30). Mounts holds
// that table, and the town-state claim's entries are internal/manifestdata's
// daemon-owned rows, so the volume seed and this package cannot disagree.
//
// The local-path provisioner does not enforce a claim's size, so a claim grows
// past its request with nothing to stop it. A claim on that class therefore
// carries gt/size-enforced: "false"; a class whose provisioner enforces the
// size carries no annotation.
//
// The Deployment runs one replica under Recreate, because two daemons must
// never hold the town's volume at once, and its pod template runs as the
// ServiceAccount daemon. The container's arguments are the live compose file's
// daemon command (liveDaemonCommand, internal/templates/daemon_compose.go). Its
// environment starts from the map the compose writer renders (ComposeSpec.Env),
// with every name decided for a pod by podEnvDecisions: the pod sets its
// container-mode pair, its stable owner name and its clock, keeps the Dolt
// endpoint and the provider settings, and drops the engine, the Mac's
// kubeconfig, the host wrapper's cloud directories and the takeover switch.
// TestPodEnvDecisions holds a decision for every live name,
// TestPodEnvEqualsTheComposeEnv holds the two services equal but for the names
// composeOnlyEnv lists, and TestPodCommandEqualsTheComposeCommand holds the
// arguments. The container carries no preStop hook:
// SIGTERM plus terminationGracePeriodSeconds is the drain, which is DrainBound's
// sum of the daemon's shutdown budget and the landing-pass drain bound.
//
// Values.Image is the digest reference read from deploy/values/images.yaml,
// which `gt update images` writes (gt-gg9hv.63); the render refuses a tag, so
// the pod runs the commit the values file records. The live Deployment carries
// gt/town-owner: pod and is not rendered without ConfirmContainerStopped: the
// Docker Desktop container owns the town until it is stopped, and only one of
// the two may own it (gt-gg9hv.30).
//
// Values.Rehearsal renders a smaller pod that may run beside the live container:
// it names its own namespace (never DefaultNamespace, the sweep's, the cache
// trim's or the Forgejo namespace), carries gt/town-owner: rehearsal, needs no
// ConfirmContainerStopped, mounts only the rehearsalSecrets entries and no
// landing work root, mounts the dolt-backup claim read-only, and binds no sweep
// or cache-trim role (gt-z4ag59, gt-e6gxt0).
//
// Values.HostGatewayIP fills the live pod's hostAliases for DoltHostName, since a
// pod has no Docker Desktop's name for the host; the operator reads the address
// from the control VM. Empty, or a rehearsal, the pod carries no alias and the
// Deployment opens with a comment saying so (gt-h6d5yb). A rehearsal runs beside
// the live container and must not reach the live Dolt server (gt-0cosuv).
//
// Values.ProxyImage gives a live pod the two socat relays the compose override
// runs beside the daemon, so the sandbox sling works from a pod as it does from
// the container; a rehearsal never renders either (gt-ygx4qd). The field's
// comment holds the contract.
//
// The bindings name the Roles and ClusterRole of deploy/k8s/sweep-rbac.yaml and
// copy no rule from it: the daemon's own kubectl calls and the sweep Job read
// through the same grants, and a manifest that renames one fails the coverage
// test rather than the first live sweep.
//
// The goldens under testdata are regenerated by
// `go test ./deploy/k8s/daemon -update`. That run compares each golden with the
// renderer's output, rewrites it, and fails, so a rewrite is reviewed before a
// run without -update passes again.
