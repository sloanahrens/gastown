var (
	dns1123LabelRE = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)
	// storageRE is the whole grammar this builder accepts: a non-zero whole
	// number and one of the four binary suffixes. It is narrower than
	// Kubernetes' own quantity grammar on purpose, and the error names what it
	// accepts.
	storageRE = regexp.MustCompile(`^[1-9][0-9]*(Ki|Mi|Gi|Ti)$`)
	// imageRefRE is the values file's daemon reference: a repository ending in
	// @sha256:<64 lowercase hex>. A tag does not match, so a pod cannot run a
	// commit the values file does not name (gt-gg9hv.63).
	imageRefRE = regexp.MustCompile(`^[a-z0-9][a-z0-9._:/-]*@sha256:[0-9a-f]{64}$`)
	// cpuRE is the container's CPU share: whole cores or millicores.
	cpuRE = regexp.MustCompile(`^[1-9][0-9]*m?$`)
	// forgeHostRE is the bare host:port the entrypoint accepts. It is the shape
	// of config.ForgeHostPattern, whose port range check follows the match; the
	// import rule keeps internal/config out of the renderer, and the parity test
	// holds the two.
	forgeHostRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*:([0-9]{1,5})$`)
	// envNameRE is an environment variable name, the shape os.Getenv reads.
	envNameRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	// envRefRE matches a ${VAR} reference, which is a name and not a literal
	// value, so an environment value carrying one is not a secret.
	envRefRE = regexp.MustCompile(`\$\{[A-Za-z_][A-Za-z0-9_]*\}`)
)

