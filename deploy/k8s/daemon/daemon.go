// The paths the pod mounts the daemon's volumes at, identical to the paths the
// compose container mounts them at, so the settings' landing work root
// (patrols.landing_worker.work_root) and the agent env blocks' GOTMPDIR and
// TMPDIR need no change at the move (gt-gg9hv.30).
const (
	TownRootPath    = "/Users/sloan/gt"
	LandingWorkPath = "/Users/sloan/gt-landing.noindex"
	TempPath        = "/Users/Shared/gt-gotmp.noindex"
)

var (
	dns1123LabelRE = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)
	// storageRE is the whole grammar this builder accepts: a non-zero whole
	// number and one of the four binary suffixes. It is narrower than
	// Kubernetes' own quantity grammar on purpose, and the error names what it
	// accepts.
	storageRE = regexp.MustCompile(`^[1-9][0-9]*(Ki|Mi|Gi|Ti)$`)
	// imageRefRE is the values file's daemon reference: a repository ending in
	// @sha256:<64 lowercase hex>. A tag does not match, so a pod cannot run a
	// commit the values file does not name (gt-gg9hv.63).
	imageRefRE = regexp.MustCompile(`^[a-z0-9][a-z0-9._:/-]*@sha256:[0-9a-f]{64}$`)
	// cpuRE is the container's CPU share: whole cores or millicores.
	cpuRE = regexp.MustCompile(`^[1-9][0-9]*m?$`)
	// forgeHostRE is the bare host:port the entrypoint accepts. It is the shape
	// of config.ForgeHostPattern, whose port range check follows the match; the
	// import rule keeps internal/config out of the renderer, and the parity test
	// holds the two.
	forgeHostRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*:([0-9]{1,5})$`)
	// envNameRE is an environment variable name, the shape os.Getenv reads.
	envNameRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	// envRefRE matches a ${VAR} reference, which is a name and not a literal
	// value, so an environment value carrying one is not a secret.
	envRefRE = regexp.MustCompile(`\$\{[A-Za-z_][A-Za-z0-9_]*\}`)
)

// The environment the render sets itself. Values.Env may not name either: the
// pod reads the town root and the config directory the render mounts, and a
// caller's value would shadow them.
const (
	TownRootEnv   = "GT_TOWN_ROOT"
	ConfigHomeEnv = "XDG_CONFIG_HOME"
)

// Mount is one volume of the daemon pod: the volume's name, the pod path it
// appears at, and the town-root entries it carries.
type Mount struct {
	// Volume is the pod volume's name, which is the claim's name for a claim.
	Volume string
	// Path is where the pod mounts the volume.
	Path string
	// Entries are the town-root-relative paths the volume carries, in
	// internal/townstate's placeholder form. Only the town-state claim carries
	// any: a work root and a scratch directory hold nothing of the town.
	Entries []string
}

// Mounts is the daemon pod's mount table, in the order the pod mounts it. Its
// town-state entries are read from internal/townstate, so the volume seed and
// the pod cannot disagree; TestMountsMatchTheTownStateManifest reports any drift.
var Mounts = mountTable(townstate.Default())

// mountTable is the pod's mount table for the split m. The town-state claim
// carries m's daemon-owned rows in m's order; the other two carry nothing of the
// town.
func mountTable(m *townstate.Manifest) []Mount {
	return []Mount{
		{Volume: TownStateClaim, Path: TownRootPath, Entries: ownedBy(m, townstate.OwnerDaemon)},
		{Volume: LandingWorkClaim, Path: LandingWorkPath},
		{Volume: TempVolume, Path: TempPath},
	}
}

// ownedBy returns the paths of m's rows owned by owner, in m's order.
func ownedBy(m *townstate.Manifest, owner townstate.Owner) []string {
	var paths []string
	for _, e := range m.Entries {
		if e.Owner == owner {
			paths = append(paths, e.Path)
		}
	}
	return paths
}

// Values is what the caller supplies.
type Values struct {
	// Namespace is the namespace every object lands in; DefaultNamespace when
	// empty.
	Namespace string
	// TownStateStorage is the town-state claim's requested size;
	// DefaultTownStateStorage when empty.
	TownStateStorage string
	// LandingWorkStorage is the landing-work claim's requested size;
	// DefaultLandingWorkStorage when empty.
	LandingWorkStorage string
	// StorageClass is the claims' storage class; DefaultStorageClass when
	// empty.
	StorageClass string
	// ForgejoService and ForgejoNamespace name the Forgejo Service in the
	// control cluster the Service resolves to. Both empty take the default
	// pair; one empty is refused, since the name is composed from both.
	ForgejoService   string
	ForgejoNamespace string
	// Secrets are the entries of deploy/daemon/secrets.yaml's files list. One
	// Secret is rendered per entry, whether or not the Deployment mounts it: an
	// unclaimed entry still gets a Secret, holding the entry's name as an empty
	// placeholder key. The renderer never receives a secret's bytes.
	Secrets []templates.SecretFile
	// Image is the daemon reference read from deploy/values/images.yaml
	// (gt-gg9hv.63): repo@sha256:<64 lowercase hex>. A tag is refused.
	Image string
	// Env is the container's environment, the same map the compose writer
	// renders (ComposeSpec.Env in internal/templates/daemon_compose.go). A value
	// that looks like a secret is refused rather than written into a manifest.
	Env map[string]string
	// OMToken mounts the OMTokenFile Secret and passes --om-token-file at
	// templates.LiveOMTokenPath, as a live compose spec with OMTokenFile does.
	OMToken bool
	// ForgeHost is the forge host:port the pod's git asks. Set, the pod mounts
	// the ForgeTokenFile Secret and passes --forge-host and
	// --forge-token-file, as a live compose spec with ForgeHost does.
	ForgeHost string
	// CPU and Memory are the container's share; requests equal limits.
	// DefaultCPU and DefaultMemory when empty.
	CPU    string
	Memory string
	// TerminationGraceSeconds is the pod's terminationGracePeriodSeconds.
	// DefaultTerminationGraceSeconds when zero; MinimumTerminationGraceSeconds is
	// the floor.
	TerminationGraceSeconds int
	// ConfirmContainerStopped is the operator's acknowledgement that the Docker
	// Desktop container is stopped. The render refuses without it: only one of
	// the container and the pod may own the town (gt-gg9hv.30).
	ConfirmContainerStopped bool
}

// Manifests is what Build returns, in the order Render writes it.
type Manifests struct {
	Namespace            Namespace
	ServiceAccount       ServiceAccount
	TownStateClaim       PersistentVolumeClaim
	LandingWorkClaim     PersistentVolumeClaim
	ForgejoService       Service
	Secrets              []Secret
	Deployment           Deployment
	SweepRoleBinding     RoleBinding
	CacheTrimRoleBinding RoleBinding
	SweepReaderBinding   ClusterRoleBinding
}

// Build returns the manifests for v, or the reason v cannot be rendered.
func Build(v Values) (Manifests, error) {
	v = v.withDefaults()
	if err := v.validate(); err != nil {
		return Manifests{}, err
	}
	namespace := v.Namespace
	if namespace == "" {
		namespace = DefaultNamespace
	}

	m := Manifests{
		Namespace: Namespace{
			TypeMeta: TypeMeta{APIVersion: "v1", Kind: "Namespace"},
			Metadata: ObjectMeta{Name: namespace, Labels: labels()},
		},
		ServiceAccount: ServiceAccount{
			TypeMeta: TypeMeta{APIVersion: "v1", Kind: "ServiceAccount"},
			Metadata: objectMeta(ServiceAccountName, namespace),
		},
		TownStateClaim:   claim(TownStateClaim, namespace, v.TownStateStorage, v.StorageClass),
		LandingWorkClaim: claim(LandingWorkClaim, namespace, v.LandingWorkStorage, v.StorageClass),
		ForgejoService: Service{
			TypeMeta: TypeMeta{APIVersion: "v1", Kind: "Service"},
			Metadata: objectMeta(ForgejoName, namespace),
			Spec: ServiceSpec{
				Type:         "ExternalName",
				ExternalName: v.ForgejoService + "." + v.ForgejoNamespace + ".svc.cluster.local",
				Ports:        []ServicePort{{Name: "http", Port: ForgejoPort, Protocol: "TCP"}},
			},
		},
		Secrets:              make([]Secret, 0, len(v.Secrets)),
		Deployment:           deployment(v, namespace),
		SweepRoleBinding:     roleBinding(Name+"-"+SweepRole, SweepNamespace, SweepRole, namespace),
		CacheTrimRoleBinding: roleBinding(Name+"-"+CacheTrimRole, CacheTrimNamespace, CacheTrimRole, namespace),
		SweepReaderBinding:   clusterRoleBinding(Name+"-"+SweepReaderRole, SweepReaderRole, namespace),
	}
	for _, file := range v.Secrets {
		m.Secrets = append(m.Secrets, secret(file, namespace))
	}
	return m, nil
}

// claim is a claim of size, on class, named name in namespace. On the class
// whose provisioner does not enforce the size it carries SizeEnforcedAnnotation,
// so an operator reading the claim is not surprised by the volume outgrowing it.
func claim(name, namespace, size, class string) PersistentVolumeClaim {
	c := PersistentVolumeClaim{
		TypeMeta: TypeMeta{APIVersion: "v1", Kind: "PersistentVolumeClaim"},
		Metadata: objectMeta(name, namespace),
		Spec: PVCSpec{
			AccessModes:      []string{"ReadWriteOnce"},
			StorageClassName: class,
			Resources:        ResourceRequirements{Requests: map[string]string{"storage": size}},
		},
	}
	if class == DefaultStorageClass {
		c.Metadata.Annotations = map[string]string{SizeEnforcedAnnotation: sizeNotEnforced}
	}
	return c
}

// secret is the Secret for one manifest entry: the entry's name as a key whose
// value is empty, so a deployment mounts the file by the key and the operator
// has a placeholder to fill.
func secret(file templates.SecretFile, namespace string) Secret {
	return Secret{
		TypeMeta: TypeMeta{APIVersion: "v1", Kind: "Secret"},
		Metadata: ObjectMeta{
			Name:        SecretNamePrefix + file.Name,
			Namespace:   namespace,
			Labels:      labels(),
			Annotations: map[string]string{SourceFileAnnotation: file.Name},
		},
		Type:       "Opaque",
		StringData: map[string]string{file.Name: ""},
	}
}

// roleBinding binds the pod's service account to role in namespace, named name.
// A RoleBinding may name a service account of another namespace, which is how
// the pod in Values.Namespace reads the sweep's grants in the sweep's own
// namespaces.
func roleBinding(name, namespace, role, serviceAccountNamespace string) RoleBinding {
	return RoleBinding{
		TypeMeta: TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "RoleBinding"},
		Metadata: objectMeta(name, namespace),
		RoleRef:  RoleRef{APIGroup: "rbac.authorization.k8s.io", Kind: "Role", Name: role},
		Subjects: []Subject{{Kind: "ServiceAccount", Name: ServiceAccountName, Namespace: serviceAccountNamespace}},
	}
}

// clusterRoleBinding binds the pod's service account to role, a ClusterRole.
func clusterRoleBinding(name, role, serviceAccountNamespace string) ClusterRoleBinding {
	return ClusterRoleBinding{
		TypeMeta: TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "ClusterRoleBinding"},
		Metadata: objectMeta(name, ""),
		RoleRef:  RoleRef{APIGroup: "rbac.authorization.k8s.io", Kind: "ClusterRole", Name: role},
		Subjects: []Subject{{Kind: "ServiceAccount", Name: ServiceAccountName, Namespace: serviceAccountNamespace}},
	}
}

// deployment is the daemon pod: one replica under Recreate, as the container is
// one service that owns the town's volume.
func deployment(v Values, namespace string) Deployment {
	return Deployment{
		TypeMeta: TypeMeta{APIVersion: "apps/v1", Kind: "Deployment"},
		Metadata: ObjectMeta{
			Name:        Name,
			Namespace:   namespace,
			Labels:      labels(),
			Annotations: map[string]string{TownOwnerAnnotation: TownOwnerPod},
		},
		Spec: DeploymentSpec{
			Replicas: 1,
			Strategy: DeploymentStrategy{Type: "Recreate"},
			Selector: LabelSelector{MatchLabels: selectorLabels()},
			Template: PodTemplate{
				Metadata: PodTemplateMeta{Labels: labels()},
				Spec: PodSpec{
					ServiceAccountName:            ServiceAccountName,
					TerminationGracePeriodSeconds: int32(v.TerminationGraceSeconds),
					Containers:                    []Container{daemonContainer(v)},
					Volumes:                       volumes(v),
				},
			},
		},
	}
}

// daemonContainer is the daemon's container. Its arguments are the live compose
// file's daemon command, so the entrypoint reads the same flags from the same
// fixed paths (templates.LiveOMTokenPath and templates.LiveForgeTokenPath).
func daemonContainer(v Values) Container {
	return Container{
		Name:       Name,
		Image:      v.Image,
		Args:       daemonArgs(v),
		WorkingDir: TownRootPath,
		Env:        containerEnvironment(v),
		Resources: ContainerResources{
			Requests: resourceList(v),
			Limits:   resourceList(v),
		},
		VolumeMounts: mounts(v),
		ReadinessProbe: &Probe{
			// gt status --line is the health line the update cycle judges a swap
			// by, and its exit code is green alone: a degraded or red town keeps
			// the pod out of readiness.
			Exec:                &ExecAction{Command: []string{"gt", "status", "--line"}},
			InitialDelaySeconds: 30,
			PeriodSeconds:       30,
			TimeoutSeconds:      10,
			FailureThreshold:    3,
		},
		LivenessProbe: &Probe{
			// gt daemon status reports whether the daemon runs, not whether the
			// town is green, so a degraded town never restarts the pod. The
			// longer period and the higher failure threshold keep one slow read
			// from killing it.
			Exec:                &ExecAction{Command: []string{"gt", "daemon", "status"}},
			InitialDelaySeconds: 60,
			PeriodSeconds:       60,
			TimeoutSeconds:      15,
			FailureThreshold:    5,
		},
		// The preStop asks the daemon to drain before the kubelet's SIGTERM, so
		// the pod finishes its in-flight work inside the grace period. gt daemon
		// drain is the drain entry point the image must carry for the hook to
		// have an effect; a binary without it only logs the failed hook before
		// the daemon shuts down on the signal.
		Lifecycle: &Lifecycle{PreStop: &LifecycleHandler{Exec: &ExecAction{Command: []string{"gt", "daemon", "drain"}}}},
	}
}

// daemonArgs is the container's argument list: the flags the image's entrypoint
// reads credentials from. The live compose render writes the same argv from
// liveDaemonCommand, and TestPodCommandEqualsTheComposeCommand holds the two
// equal.
func daemonArgs(v Values) []string {
	var args []string
	if v.OMToken {
		args = append(args, "--om-token-file", templates.LiveOMTokenPath)
	}
	if v.ForgeHost != "" {
		args = append(args, "--forge-host", v.ForgeHost, "--forge-token-file", templates.LiveForgeTokenPath)
	}
	return args
}

// containerEnvironment is GT_TOWN_ROOT and XDG_CONFIG_HOME at the mounted
// paths, then the caller's environment sorted. The daemon resolves its config
// directory through XDG_CONFIG_HOME, which is where the Secrets are mounted.
func containerEnvironment(v Values) []EnvVar {
	env := []EnvVar{
		{Name: TownRootEnv, Value: TownRootPath},
		{Name: ConfigHomeEnv, Value: templates.LiveOpenShellConfigHome},
	}
	for _, name := range sortedKeys(v.Env) {
		env = append(env, EnvVar{Name: name, Value: v.Env[name]})
	}
	return env
}

// resourceList is the container's CPU and memory share.
func resourceList(v Values) map[string]string {
	return map[string]string{"cpu": v.CPU, "memory": v.Memory}
}

// volumes are the claims at the container's paths, the scratch emptyDir, and
// one volume per rendered Secret. A Secret volume is named after its file with
// the dots of a file name replaced, since a volume name is a DNS-1123 label.
func volumes(v Values) []Volume {
	vols := []Volume{
		{Name: TownStateClaim, PersistentVolumeClaim: &PVCVolumeSource{ClaimName: TownStateClaim}},
		{Name: LandingWorkClaim, PersistentVolumeClaim: &PVCVolumeSource{ClaimName: LandingWorkClaim}},
		{Name: TempVolume, EmptyDir: &EmptyDirVolumeSource{}},
	}
	for _, file := range v.Secrets {
		vols = append(vols, Volume{
			Name:   secretVolumeName(file.Name),
			Secret: &SecretVolumeSource{SecretName: SecretNamePrefix + file.Name},
		})
	}
	return vols
}

// mounts place each volume at the path the container uses. Each config file is
// a subPath mount of its Secret's one key, at the XDG config directory the
// daemon resolves its token files through; the two credential files are also
// mounted at the fixed paths the command line names.
func mounts(v Values) []VolumeMount {
	m := []VolumeMount{
		{Name: TownStateClaim, MountPath: TownRootPath},
		{Name: LandingWorkClaim, MountPath: LandingWorkPath},
		{Name: TempVolume, MountPath: TempPath},
	}
	for _, file := range v.Secrets {
		m = append(m, VolumeMount{
			Name:      secretVolumeName(file.Name),
			MountPath: templates.LiveConfigDirPath + "/" + file.Name,
			SubPath:   file.Name,
			ReadOnly:  true,
		})
	}
	if v.OMToken {
		m = append(m, VolumeMount{
			Name:      secretVolumeName(OMTokenFile),
			MountPath: templates.LiveOMTokenPath,
			SubPath:   OMTokenFile,
			ReadOnly:  true,
		})
	}
	if v.ForgeHost != "" {
		m = append(m, VolumeMount{
			Name:      secretVolumeName(ForgeTokenFile),
			MountPath: templates.LiveForgeTokenPath,
			SubPath:   ForgeTokenFile,
			ReadOnly:  true,
		})
	}
	return m
}

// secretVolumeName is the pod volume for a Secret of file: a DNS-1123 label.
// The render refuses two files whose volumes collide.
func secretVolumeName(file string) string {
	return strings.ReplaceAll(SecretNamePrefix+file, ".", "-")
}

// selectorLabels are what the Deployment selects its pods by: the name alone.
func selectorLabels() map[string]string {
	return map[string]string{"app.kubernetes.io/name": Name}
}

// sortedKeys returns m's keys in order, so the rendered environment does not
// depend on map iteration.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// objectMeta is the metadata every namespaced object carries. Each call builds
// its own label map, so editing one object's labels leaves the others alone.
func objectMeta(name, namespace string) ObjectMeta {
	return ObjectMeta{Name: name, Namespace: namespace, Labels: labels()}
}

// labels are on every object.
func labels() map[string]string {
	return map[string]string{
		"app.kubernetes.io/name":       Name,
		"app.kubernetes.io/managed-by": "gt",
	}
}

func (v Values) withDefaults() Values {
	if v.TownStateStorage == "" {
		v.TownStateStorage = DefaultTownStateStorage
	}
	if v.LandingWorkStorage == "" {
		v.LandingWorkStorage = DefaultLandingWorkStorage
	}
	if v.StorageClass == "" {
		v.StorageClass = DefaultStorageClass
	}
	if v.ForgejoService == "" && v.ForgejoNamespace == "" {
		v.ForgejoService = DefaultForgejoService
		v.ForgejoNamespace = DefaultForgejoNamespace
	}
	if v.CPU == "" {
		v.CPU = DefaultCPU
	}
	if v.Memory == "" {
		v.Memory = DefaultMemory
	}
	if v.TerminationGraceSeconds == 0 {
		v.TerminationGraceSeconds = DefaultTerminationGraceSeconds
	}
	return v
}

func (v Values) validate() error {
	if v.Namespace != "" && !validDNS1123Label(v.Namespace) {
		return fmt.Errorf("Values.Namespace %q: want a DNS-1123 label of at most 63 characters, such as gt", v.Namespace)
	}
	if !storageRE.MatchString(v.TownStateStorage) {
		return fmt.Errorf("Values.TownStateStorage %q: want a non-zero whole number and one of Ki, Mi, Gi or Ti, such as 20Gi", v.TownStateStorage)
	}
	if !storageRE.MatchString(v.LandingWorkStorage) {
		return fmt.Errorf("Values.LandingWorkStorage %q: want a non-zero whole number and one of Ki, Mi, Gi or Ti, such as 20Gi", v.LandingWorkStorage)
	}
	if !validDNS1123Subdomain(v.StorageClass) {
		return fmt.Errorf("Values.StorageClass %q: want a DNS-1123 subdomain of at most 253 characters, such as local-path", v.StorageClass)
	}
	switch {
	case v.ForgejoService == "":
		return errors.New("Values.ForgejoService is empty: name the Forgejo Service in the control cluster, or leave both Forgejo fields empty for the default pair")
	case v.ForgejoNamespace == "":
		return errors.New("Values.ForgejoNamespace is empty: name the namespace of the Forgejo Service in the control cluster, or leave both Forgejo fields empty for the default pair")
	case !validDNS1123Label(v.ForgejoService):
		return fmt.Errorf("Values.ForgejoService %q: want a DNS-1123 label of at most 63 characters, such as forgejo", v.ForgejoService)
	case !validDNS1123Label(v.ForgejoNamespace):
		return fmt.Errorf("Values.ForgejoNamespace %q: want a DNS-1123 label of at most 63 characters, such as forgejo", v.ForgejoNamespace)
	}
	if err := v.validateSecrets(); err != nil {
		return err
	}
	return v.validateDaemon()
}

// validateDaemon refuses what the Deployment cannot be rendered from: an image
// that is not a digest, a missing single-owner acknowledgement, a credential
// the Secrets list does not carry, a share or grace outside its grammar, and an
// environment entry the render cannot write.
func (v Values) validateDaemon() error {
	switch {
	case !imageRefRE.MatchString(v.Image):
		return fmt.Errorf("Values.Image %q: want the daemon image by digest (repo@sha256:<64 lowercase hex>) from deploy/values/images.yaml; a tag is refused so the pod runs the commit the values file records", v.Image)
	case !v.ConfirmContainerStopped:
		return errors.New("Values.ConfirmContainerStopped is false: the Docker Desktop container owns the town until it is stopped, so the Deployment is not rendered until the operator confirms the container is down")
	case !cpuRE.MatchString(v.CPU):
		return fmt.Errorf("Values.CPU %q: want a positive whole number of cores or millicores, such as 2 or 500m", v.CPU)
	case !storageRE.MatchString(v.Memory):
		return fmt.Errorf("Values.Memory %q: want a non-zero whole number and one of Ki, Mi, Gi or Ti, such as 4Gi", v.Memory)
	case v.TerminationGraceSeconds < MinimumTerminationGraceSeconds:
		return fmt.Errorf("Values.TerminationGraceSeconds %d: want at least %d, the daemon's landing-pass drain bound, or the pod is SIGKILLed mid-drain", v.TerminationGraceSeconds, MinimumTerminationGraceSeconds)
	}
	if err := v.validateCredentials(); err != nil {
		return err
	}
	if err := v.validateEnv(); err != nil {
		return err
	}
	return v.validateVolumes()
}

// validateCredentials holds the two mounts the command line names to the
// Secrets the render writes: a flag whose Secret is absent names a file the pod
// would never have.
func (v Values) validateCredentials() error {
	has := make(map[string]bool, len(v.Secrets))
	for _, file := range v.Secrets {
		has[file.Name] = true
	}
	if v.OMToken && !has[OMTokenFile] {
		return fmt.Errorf("Values.OMToken is true and Values.Secrets has no %q entry: the pod would mount a Secret the render never wrote", OMTokenFile)
	}
	if v.ForgeHost == "" {
		return nil
	}
	if !has[ForgeTokenFile] {
		return fmt.Errorf("Values.ForgeHost is %q and Values.Secrets has no %q entry: the pod would mount a Secret the render never wrote", v.ForgeHost, ForgeTokenFile)
	}
	if err := validForgeHost(v.ForgeHost); err != nil {
		return fmt.Errorf("Values.ForgeHost %q: %w", v.ForgeHost, err)
	}
	return nil
}

// validForgeHost refuses a host the entrypoint would refuse: the container's
// command line carries it, and the entrypoint checks the same shape
// (config.ForgeHostPattern), so the render cannot write a pod that starts and
// then refuses its own argument.
func validForgeHost(host string) error {
	m := forgeHostRE.FindStringSubmatch(host)
	if m == nil {
		return errors.New("want a bare host:port (no scheme, path, login, space or leading dash)")
	}
	port, err := strconv.Atoi(m[1])
	if err != nil || port < 1 || port > 65535 {
		return errors.New("has a port that is not 1 to 65535")
	}
	return nil
}

// validateEnv refuses an environment entry the render cannot write: a key that
// is not a variable name, a key the render sets itself, or a value that looks
// like a secret. The refusal names the key and never the value.
func (v Values) validateEnv() error {
	for _, name := range sortedKeys(v.Env) {
		switch {
		case !envNameRE.MatchString(name):
			return fmt.Errorf("Values.Env[%q]: want an environment variable name", name)
		case name == TownRootEnv || name == ConfigHomeEnv:
			return fmt.Errorf("Values.Env[%q]: the render sets this variable itself from the mount it writes", name)
		case looksLikeSecret(name, v.Env[name]):
			return fmt.Errorf("Values.Env[%q]: the value looks like a secret; the pod reads credentials from its mounted Secrets, so the manifest never carries one", name)
		}
	}
	return nil
}

// validateVolumes refuses two Secret files whose volume names collide or do not
// fit a volume name, since the pod could not mount both.
func (v Values) validateVolumes() error {
	seen := make(map[string]string, len(v.Secrets))
	for _, file := range v.Secrets {
		name := secretVolumeName(file.Name)
		if len(name) > 63 {
			return fmt.Errorf("Values.Secrets %q: the volume name %q is longer than 63 characters", file.Name, name)
		}
		if other, ok := seen[name]; ok {
			return fmt.Errorf("Values.Secrets %q and %q: both render the volume name %q", other, file.Name, name)
		}
		seen[name] = file.Name
	}
	return nil
}

// validateSecrets refuses the entries a Secret cannot be rendered from. The
// entries are re-checked because Values is a caller's value: the renderer does
// not trust the manifest parser to have run.
func (v Values) validateSecrets() error {
	if len(v.Secrets) == 0 {
		return errors.New("Values.Secrets is empty: name at least one entry of deploy/daemon/secrets.yaml, or the daemon would render with no token")
	}
	seen := make(map[string]bool, len(v.Secrets))
	for i, file := range v.Secrets {
		if err := validSecretFileName(file.Name); err != nil {
			return fmt.Errorf("Values.Secrets[%d] %q %w", i, file.Name, err)
		}
		if seen[file.Name] {
			return fmt.Errorf("Values.Secrets[%d] %q: the entry is listed more than once, and two Secrets would share a name", i, file.Name)
		}
		seen[file.Name] = true
		if name := SecretNamePrefix + file.Name; !validDNS1123Subdomain(name) {
			return fmt.Errorf("Values.Secrets[%d] %q: the Secret name %q is not a DNS-1123 subdomain", i, file.Name, name)
		}
	}
	return nil
}

// validSecretFileName refuses a name that is not one plain file in the config
// directory. An absolute path, a separator or a .. would make the rendered
// Secret name, or the file the operator fills it from, name something else.
func validSecretFileName(name string) error {
	switch {
	case name == "":
		return errors.New("has no name")
	case strings.HasPrefix(name, "/"):
		return errors.New("is an absolute path; the manifest lists a file in the config directory")
	case strings.ContainsAny(name, `/\`):
		return errors.New("names a path, not a file in the config directory")
	case name == "." || name == "..":
		return errors.New("is . or .., which name no file in the config directory")
	case strings.ContainsFunc(name, func(r rune) bool { return r < 0x20 || r == 0x7f }):
		return errors.New("holds a control character, which no file name can carry")
	}
	return nil
}

// The secret-look rule is config.LooksLikeSecret's (internal/config/secrets.go),
// restated here because the import rule keeps internal/config out of the
// renderer. TestLooksLikeSecretMatchesConfig holds the two to one table; a
// change to either without the other fails it.
const minSecretLen = 16

var (
	// secretValuePrefixes start the tokens of common providers.
	secretValuePrefixes = []string{
		"sk-", "sk_", "ghp_", "gho_", "ghu_", "ghs_", "github_pat_", "glpat-",
		"xoxb-", "xoxp-", "xapp-", "AKIA", "AIza", "ya29.",
	}
	// secretKeyMarkers mark an env key whose value is a credential.
	secretKeyMarkers = []string{
		"TOKEN", "API_KEY", "APIKEY", "SECRET", "PASSWORD", "PASSWD", "PASSPHRASE",
		"ACCESS_KEY", "PRIVATE_KEY",
	}
	// temporaryKeyIDShape is an AWS temporary access key ID: ASIA and then only
	// upper-case letters and digits.
	temporaryKeyIDRE = regexp.MustCompile(`^ASIA[0-9A-Z]+$`)
)

// looksLikeSecret reports whether value, set for env key, is a literal token:
// at least minSecretLen characters with no whitespace, not a reference, a path,
// a URL or a number, and either starting with a known token prefix or set for a
// key that names a credential.
func looksLikeSecret(key, value string) bool {
	v := strings.TrimSpace(value)
	if len(v) < minSecretLen || strings.ContainsAny(v, " \t\n") {
		return false
	}
	if envRefRE.MatchString(v) || strings.HasPrefix(v, "/") || strings.HasPrefix(v, "~") || strings.Contains(v, "://") {
		return false
	}
	if strings.Trim(v, "0123456789") == "" {
		return false
	}
	for _, p := range secretValuePrefixes {
		if strings.HasPrefix(v, p) {
			return true
		}
	}
	if temporaryKeyIDRE.MatchString(v) {
		return true
	}
	k := strings.ToUpper(key)
	for _, m := range secretKeyMarkers {
		if strings.Contains(k, m) {
			return true
		}
	}
	return false
}

// validDNS1123Label reports whether name is a DNS-1123 label: lowercase
// alphanumerics and interior hyphens, at most 63 characters.
func validDNS1123Label(name string) bool {
	return len(name) <= 63 && dns1123LabelRE.MatchString(name)
}

// validDNS1123Subdomain reports whether name is a DNS-1123 subdomain: labels
// joined by dots, at most 253 characters.
func validDNS1123Subdomain(name string) bool {
	if len(name) > 253 {
		return false
	}
	for _, label := range strings.Split(name, ".") {
		if !validDNS1123Label(label) {
			return false
		}
	}
	return true
}

// Render writes m to w as one multi-document YAML stream, or returns the reason
// the stream could not be written.
func Render(w io.Writer, m Manifests) error {
	docs := make([]any, 0, 9+len(m.Secrets))
	docs = append(docs, m.Namespace, m.ServiceAccount, m.TownStateClaim, m.LandingWorkClaim, m.ForgejoService)
	for _, s := range m.Secrets {
		docs = append(docs, s)
	}
	docs = append(docs, m.Deployment, m.SweepRoleBinding, m.CacheTrimRoleBinding, m.SweepReaderBinding)
	return encode(w, docs...)
}

// YAML writes v to w as one YAML document, or returns the reason it could not
// be written.
func YAML(w io.Writer, v any) error {
	return encode(w, v)
}

// encode writes each document in order. Close reports a failed document's write
// error a second time, so the first error is the one kept.
func encode(w io.Writer, docs ...any) error {
	enc := yaml.NewEncoder(w)
	enc.SetIndent(2)
	var err error
	for _, doc := range docs {
		if err = enc.Encode(doc); err != nil {
			break
		}
	}
	if closeErr := enc.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		return fmt.Errorf("encoding the manifest: %w", err)
	}
	return nil
}

// TypeMeta is the apiVersion and kind every object carries.
type TypeMeta struct {
	APIVersion string `yaml:"apiVersion"`
	Kind       string `yaml:"kind"`
}

// ObjectMeta is the subset of an object's metadata the manifests set.
type ObjectMeta struct {
	Name        string            `yaml:"name"`
	Namespace   string            `yaml:"namespace,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Annotations map[string]string `yaml:"annotations,omitempty"`
}

// Namespace is the cluster-scoped v1 Namespace the other objects land in.
type Namespace struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta `yaml:"metadata"`
}

// PersistentVolumeClaim is the subset of v1's PersistentVolumeClaim the builder
// renders.
type PersistentVolumeClaim struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta `yaml:"metadata"`
	Spec     PVCSpec    `yaml:"spec"`
}

// PVCSpec is the subset of a claim's spec the builder sets.
type PVCSpec struct {
	AccessModes      []string             `yaml:"accessModes"`
	StorageClassName string               `yaml:"storageClassName"`
	Resources        ResourceRequirements `yaml:"resources"`
}

// ResourceRequirements is the claim's requested storage.
type ResourceRequirements struct {
	Requests map[string]string `yaml:"requests"`
}

// Service is the subset of v1's Service the builder renders.
type Service struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta  `yaml:"metadata"`
	Spec     ServiceSpec `yaml:"spec"`
}

// ServiceSpec is the subset of a Service's spec the builder sets. An
// ExternalName Service answers with the target's DNS record, so it selects no
// pod; the ports are published for a reader, not forwarded.
type ServiceSpec struct {
	Type         string        `yaml:"type"`
	ExternalName string        `yaml:"externalName"`
	Ports        []ServicePort `yaml:"ports"`
}

// ServicePort is one port the Service publishes.
type ServicePort struct {
	Name     string `yaml:"name"`
	Port     int32  `yaml:"port"`
	Protocol string `yaml:"protocol"`
}

// Secret is the subset of v1's Secret the builder renders: one placeholder key
// and no value.
type Secret struct {
	TypeMeta   `yaml:",inline"`
	Metadata   ObjectMeta        `yaml:"metadata"`
	Type       string            `yaml:"type"`
	StringData map[string]string `yaml:"stringData"`
}

// ServiceAccount is the v1 ServiceAccount the pod runs as.
type ServiceAccount struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta `yaml:"metadata"`
}

// RoleBinding is the subset of rbac.authorization.k8s.io/v1's RoleBinding the
// builder renders: one RoleRef and the daemon's service account.
type RoleBinding struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta `yaml:"metadata"`
	RoleRef  RoleRef    `yaml:"roleRef"`
	Subjects []Subject  `yaml:"subjects"`
}

// ClusterRoleBinding is the same shape, cluster-scoped.
type ClusterRoleBinding struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta `yaml:"metadata"`
	RoleRef  RoleRef    `yaml:"roleRef"`
	Subjects []Subject  `yaml:"subjects"`
}

// RoleRef names the Role or ClusterRole a binding grants.
type RoleRef struct {
	APIGroup string `yaml:"apiGroup"`
	Kind     string `yaml:"kind"`
	Name     string `yaml:"name"`
}

// Subject is one holder of a binding's grant.
type Subject struct {
	Kind      string `yaml:"kind"`
	Name      string `yaml:"name"`
	Namespace string `yaml:"namespace,omitempty"`
}

// Deployment is the subset of apps/v1's Deployment the builder renders.
type Deployment struct {
	TypeMeta `yaml:",inline"`
	Metadata ObjectMeta     `yaml:"metadata"`
	Spec     DeploymentSpec `yaml:"spec"`
}

// DeploymentSpec is the subset of a Deployment's spec the builder sets.
type DeploymentSpec struct {
	Replicas int32              `yaml:"replicas"`
	Strategy DeploymentStrategy `yaml:"strategy"`
	Selector LabelSelector      `yaml:"selector"`
	Template PodTemplate        `yaml:"template"`
}

// DeploymentStrategy is how a rollout replaces the pod; Recreate stops the old
// pod before the new one starts, so two daemons never hold the town's volume.
type DeploymentStrategy struct {
	Type string `yaml:"type"`
}

// LabelSelector is the subset of a selector the Deployment sets.
type LabelSelector struct {
	MatchLabels map[string]string `yaml:"matchLabels"`
}

// PodTemplate is the pod the Deployment creates.
type PodTemplate struct {
	Metadata PodTemplateMeta `yaml:"metadata"`
	Spec     PodSpec         `yaml:"spec"`
}

// PodTemplateMeta is the pod's labels; a template carries no name or namespace.
type PodTemplateMeta struct {
	Labels map[string]string `yaml:"labels"`
}

// PodSpec is the subset of a pod's spec the builder sets.
type PodSpec struct {
	ServiceAccountName            string      `yaml:"serviceAccountName"`
	TerminationGracePeriodSeconds int32       `yaml:"terminationGracePeriodSeconds"`
	Containers                    []Container `yaml:"containers"`
	Volumes                       []Volume    `yaml:"volumes,omitempty"`
}

// Container is the subset of one container the builder sets.
type Container struct {
	Name           string             `yaml:"name"`
	Image          string             `yaml:"image"`
	Args           []string           `yaml:"args,omitempty"`
	WorkingDir     string             `yaml:"workingDir,omitempty"`
	Env            []EnvVar           `yaml:"env,omitempty"`
	Resources      ContainerResources `yaml:"resources"`
	VolumeMounts   []VolumeMount      `yaml:"volumeMounts,omitempty"`
	ReadinessProbe *Probe             `yaml:"readinessProbe,omitempty"`
	LivenessProbe  *Probe             `yaml:"livenessProbe,omitempty"`
	Lifecycle      *Lifecycle         `yaml:"lifecycle,omitempty"`
}

// EnvVar is one environment entry.
type EnvVar struct {
	Name  string `yaml:"name"`
	Value string `yaml:"value"`
}

// ContainerResources is a container's share. Requests equal limits, so the
// scheduler promises it the share instead of letting it burst into a neighbour.
type ContainerResources struct {
	Requests map[string]string `yaml:"requests"`
	Limits   map[string]string `yaml:"limits"`
}

// VolumeMount is where one volume appears in the container. A subPath mounts one
// key of a Secret volume as a single file.
type VolumeMount struct {
	Name      string `yaml:"name"`
	MountPath string `yaml:"mountPath"`
	SubPath   string `yaml:"subPath,omitempty"`
	ReadOnly  bool   `yaml:"readOnly,omitempty"`
}

// Volume is one pod volume: a claim, an emptyDir or a Secret.
type Volume struct {
	Name                  string                `yaml:"name"`
	PersistentVolumeClaim *PVCVolumeSource      `yaml:"persistentVolumeClaim,omitempty"`
	EmptyDir              *EmptyDirVolumeSource `yaml:"emptyDir,omitempty"`
	Secret                *SecretVolumeSource   `yaml:"secret,omitempty"`
}

// PVCVolumeSource names the claim a volume carries.
type PVCVolumeSource struct {
	ClaimName string `yaml:"claimName"`
}

// EmptyDirVolumeSource is an emptyDir with no medium or size limit.
type EmptyDirVolumeSource struct{}

// SecretVolumeSource names the Secret a volume carries.
type SecretVolumeSource struct {
	SecretName string `yaml:"secretName"`
}

// Probe is a readiness or liveness check: a command whose zero exit passes.
type Probe struct {
	Exec                *ExecAction `yaml:"exec,omitempty"`
	InitialDelaySeconds int32       `yaml:"initialDelaySeconds,omitempty"`
	PeriodSeconds       int32       `yaml:"periodSeconds,omitempty"`
	TimeoutSeconds      int32       `yaml:"timeoutSeconds,omitempty"`
	FailureThreshold    int32       `yaml:"failureThreshold,omitempty"`
}

// ExecAction is a probe or hook command.
type ExecAction struct {
	Command []string `yaml:"command"`
}

// Lifecycle is the pod's lifecycle hooks.
type Lifecycle struct {
	PreStop *LifecycleHandler `yaml:"preStop,omitempty"`
}

// LifecycleHandler is one lifecycle hook.
type LifecycleHandler struct {
	Exec *ExecAction `yaml:"exec,omitempty"`
}
