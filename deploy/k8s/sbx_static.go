package k8s

import (
	"embed"
	"errors"
	"fmt"
	"io/fs"
)

// sbxStaticFileNames is the order SbxStatic returns the gt-sbx files' documents
// in, after the priority classes. The //go:embed directive is the one list of
// what is embedded; this holds only the order, and TestSbxStaticEmbeddedFilesWalk
// fails when the two hold different files.
var sbxStaticFileNames = []string{
	"values/kind/control-plane-services.yaml",
	"kind/gateway-nodeport.yaml",
	"gt-cache/claim.yaml",
}

//go:embed values/kind/control-plane-services.yaml kind/gateway-nodeport.yaml gt-cache/claim.yaml
var sbxStaticManifests embed.FS

// SbxStatic returns the objects the gt-sbx cluster applies, in apply order: the
// priority classes the control cluster applies from priority-classes.yaml, then
// the control-plane Services, the gateway's NodePort Service and the Go cache
// claim.
func SbxStatic() ([]StaticObject, error) {
	return sbxStaticObjects(Static, sbxStaticManifests, sbxStaticFileNames)
}

// sbxStaticObjects is SbxStatic over an injected control-cluster set and file
// system, so a test can hold the refusal for a set with no priority class.
func sbxStaticObjects(controlStatic func() ([]StaticObject, error), fsys fs.FS, files []string) ([]StaticObject, error) {
	control, err := controlStatic()
	if err != nil {
		return nil, fmt.Errorf("reading the control cluster's static set: %w", err)
	}
	var objects []StaticObject
	for _, obj := range control {
		if obj.Kind == "PriorityClass" {
			objects = append(objects, obj)
		}
	}
	// OpenShell admits the gt-sandbox class and the cluster's workloads are
	// ordered by the classes, so a set without them is a broken input rather
	// than a cluster that needs no classes.
	if len(objects) == 0 {
		return nil, errors.New("the control cluster's static set holds no PriorityClass, which gt-sbx applies first")
	}
	sbx, err := staticObjects(fsys, files)
	if err != nil {
		return nil, err
	}
	return append(objects, sbx...), nil
}

// SbxExcluded lists every file under the gt-sbx set's paths that SbxStatic does
// not embed, with the owner who decides it and why it is not an applied object.
// A new bootstrap or hand-applied file joins this list or the embedded set, or
// the accounting test fails.
var SbxExcluded = []struct{ File, Owner, Reason string }{
	{"deploy/k8s/kind/cluster.yaml", "bootstrap", "the kind cluster config up.sh fills and passes to kind create"},
	{"deploy/k8s/kind/common.sh", "bootstrap", "the shell helpers up.sh and down.sh source"},
	{"deploy/k8s/kind/up.sh", "bootstrap", "creates the cluster, before any object exists to apply"},
	{"deploy/k8s/kind/down.sh", "bootstrap", "deletes the cluster"},
	{"deploy/k8s/kind/kind_test.sh", "bootstrap", "the script that exercises up.sh and down.sh"},
	{"deploy/k8s/values/kind.yaml", "the renderer", "the OpenShell chart's values, an input, not an object"},
	{"deploy/k8s/values/kind/hosts.yaml", "the renderer", "the per-environment input control-plane-services.yaml is generated from"},
	{"deploy/k8s/values/kind/registry-forward.yaml", "overseer", "generated by render-services; up.sh does not read it, and no file records who applies it"},
}
