// isolateGit gives git an environment that is the throwaway repository's and nothing
// else: no global or system config, a fixed identity, and no inherited repository
// location, so the commit and tag do not depend on the host.
func isolateGit(t *testing.T) {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", home)
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	t.Setenv("GIT_AUTHOR_NAME", "bump-version test")
	t.Setenv("GIT_AUTHOR_EMAIL", "bump-version@example.invalid")
	t.Setenv("GIT_COMMITTER_NAME", "bump-version test")
	t.Setenv("GIT_COMMITTER_EMAIL", "bump-version@example.invalid")
	for _, name := range []string{"GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"} {
		t.Setenv(name, "")
		_ = os.Unsetenv(name)
	}
}

// gitIn runs git in dir with the test's environment and returns its trimmed standard
// output, failing the test when git exits non-zero.
func gitIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("git %s: %v", strings.Join(args, " "), err)
	}
	return strings.TrimSpace(string(out))
}

// TestIntegrationRunCommitsAndTagsTheRepository drives the command through the real file,
// git and environment seams over a throwaway repository. The process is started from a
// directory that is not the repository, so the run must find every file through its root.
// make and gt are faked at the process seam and nix is absent. The three version files are
// edited, the commit and tag are made, and no git push is run.
func TestIntegrationRunCommitsAndTagsTheRepository(t *testing.T) {
	isolateGit(t)
	root := t.TempDir()
	t.Chdir(t.TempDir())

	gitIn(t, root, "init", "-q")
	files := map[string]string{
		"internal/cmd/version.go":  "package cmd\n\nvar (\n\tVersion = \"1.2.1\"\n)\n",
		"npm-package/package.json": "{\n  \"version\": \"1.2.1\"\n}\n",
		"CHANGELOG.md":             "# Changelog\n\n## [Unreleased]\n\n- Initial work.\n",
	}
	for name, text := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	gitIn(t, root, "add", "-A")
	gitIn(t, root, "commit", "-q", "-m", "fixture")

	env := systemEnv(root)
	var out bytes.Buffer
	env.Out = &out
	env.Date = "2026-10-30"

	var makes int
	runProcessReal := env.Exec.Run
	env.Exec.Run = func(dir string, extra []string, name string, args ...string) ([]byte, []byte, error) {
		switch name {
		case "make":
			makes++
			return nil, nil, nil
		case "gt":
			return []byte("gt version 1.3.0\n"), nil, nil
		}
		return runProcessReal(dir, extra, name, args...)
	}
	lookPath := env.Exec.LookPath
	env.Exec.LookPath = func(file string) (string, error) {
		if file == "nix" {
			return "", exec.ErrNotFound
		}
		return lookPath(file)
	}
	var gitCalls [][]string
	runGitReal := env.Git.Run
	env.Git.Run = func(dir string, args ...string) (int, error) {
		gitCalls = append(gitCalls, args)
		return runGitReal(dir, args...)
	}

	var errw bytes.Buffer
	if code := run([]string{"1.3.0", "--commit", "--tag", "--install"}, env, &errw); code != 0 {
		t.Fatalf("run exit = %d, want 0; error stream:\n%s\noutput:\n%s", code, errw.String(), out.String())
	}

	if makes != 1 {
		t.Errorf("make install ran %d times, want 1", makes)
	}
	if !strings.Contains(out.String(), "✓ Verified: gt version 1.3.0") {
		t.Errorf("output lacks the verified install line:\n%s", out.String())
	}
	if !strings.HasSuffix(out.String(), "Summary:\nCommitted and tagged v1.3.0.\n") {
		t.Errorf("output does not end with the summary:\n%s", out.String())
	}

	edits := map[string]string{
		"internal/cmd/version.go":  `Version = "1.3.0"`,
		"npm-package/package.json": `"version": "1.3.0"`,
		"CHANGELOG.md":             "## [1.3.0] - 2026-10-30",
	}
	for name, want := range edits {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), want) {
			t.Errorf("%s after the run lacks %q:\n%s", name, want, data)
		}
	}

	wantMessage := "chore: Bump version to 1.3.0\n\n" +
		"Updated all component versions:\n" +
		"- gt CLI: 1.2.1 → 1.3.0\n" +
		"- npm package: 1.2.1 → 1.3.0\n\n" +
		"Generated by bump-version"
	if got := gitIn(t, root, "log", "-1", "--format=%B"); got != wantMessage {
		t.Errorf("commit message = %q, want %q", got, wantMessage)
	}
	wantFiles := "CHANGELOG.md\ninternal/cmd/version.go\nnpm-package/package.json"
	if got := gitIn(t, root, "show", "--name-only", "--format=", "HEAD"); got != wantFiles {
		t.Errorf("files in the commit = %q, want %q", got, wantFiles)
	}
	if got := gitIn(t, root, "cat-file", "-t", "v1.3.0"); got != "tag" {
		t.Errorf("tag object type = %q, want an annotated tag object", got)
	}
	if got := gitIn(t, root, "status", "--porcelain"); got != "" {
		t.Errorf("working tree after the commit = %q, want clean", got)
	}
	if got := gitIn(t, root, "remote"); got != "" {
		t.Errorf("git remote = %q, want no remote to push to", got)
	}
	for _, args := range gitCalls {
		if args[0] == "push" {
			t.Errorf("the run ran git %s; the command never pushes", strings.Join(args, " "))
		}
	}
}
