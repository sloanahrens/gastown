package bumpversion

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"path/filepath"
	"regexp"
	"strings"
)

// Git is the git seam for the dirty-tree check, the commit and the tag. Run
// executes git with args in dir and returns its exit status. err is set only when
// git could not be started, so a status of 128 from a repository that is not one
// comes back as a code, not as a clean tree. Output is not returned: the steps
// need to know whether git succeeded, and git's output can hold anything.
type Git struct {
	Run func(dir string, args ...string) (code int, err error)
}

// dirtyExit is the status git diff-index --quiet exits with when the tree differs
// from HEAD. Any other non-zero status is a git failure, not a dirty tree.
const dirtyExit = 1

// Release is the version change the commit and the tag record: the version the
// tree had, the version the edits wrote, and whether nix is on PATH, which decides
// whether the commit names flake.nix.
type Release struct {
	Old string
	New string
	Nix bool
}

// CheckTree is the dirty-tree rule, run before any file is edited. A clean tree
// passes. A dirty tree is refused under --commit, because the commit would take the
// operator's changes with the version bump. Without --commit it is refused unless
// --allow-dirty was given, which stands in for the script's interactive Continue
// anyway? prompt. A git that fails for any other reason is an error, never clean.
func CheckTree(g Git, root string, opts Options, out io.Writer) error {
	code, err := g.Run(root, "diff-index", "--quiet", "HEAD", "--")
	if err != nil {
		return fmt.Errorf("git diff-index: %w", err)
	}
	switch code {
	case 0:
		return nil
	case dirtyExit:
	default:
		return fmt.Errorf("git diff-index: exit %d", code)
	}
	fmt.Fprintln(out, "Warning: You have uncommitted changes")
	if opts.Commit {
		return &Refusal{Msg: "Error: Cannot auto-commit with existing uncommitted changes"}
	}
	if !opts.AllowDirty {
		return &Refusal{Msg: "Error: uncommitted changes (pass --allow-dirty to continue over them)"}
	}
	return nil
}

// Commit stages the version files and commits them with the release message. The
// two Go and npm files are always staged. flake.nix is staged only when nix is on
// PATH and the file exists, and CHANGELOG.md only when it exists, since a repository
// without one has nothing to stage. A file that cannot be read is an error, so an
// unreadable flake.nix is never silently left out of the commit.
func Commit(g Git, fsys FS, root string, r Release) error {
	paths := []string{VersionGoPath, PackageJSONPath}
	if r.Nix {
		ok, err := present(fsys, FlakePath)
		if err != nil {
			return err
		}
		if ok {
			paths = append(paths, FlakePath)
		}
	}
	ok, err := present(fsys, ChangelogPath)
	if err != nil {
		return err
	}
	if ok {
		paths = append(paths, ChangelogPath)
	}
	if err := gitRun(g, root, append([]string{"add"}, paths...)...); err != nil {
		return err
	}
	return gitRun(g, root, "commit", "-m", commitMessage(r))
}

// present reports whether name exists in fsys. A read that fails for any reason
// other than a missing file is an error, not an absent file.
func present(fsys FS, name string) (bool, error) {
	_, err := fsys.ReadFile(name)
	if err == nil {
		return true, nil
	}
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return false, fmt.Errorf("read %s: %w", name, err)
}

// commitMessage is the script's commit message. The flake.nix line appears only when
// nix is on PATH, because that is when flake.nix was bumped.
func commitMessage(r Release) string {
	var b strings.Builder
	fmt.Fprintf(&b, "chore: Bump version to %s\n\n", r.New)
	fmt.Fprintf(&b, "Updated all component versions:\n")
	fmt.Fprintf(&b, "- gt CLI: %s → %s\n", r.Old, r.New)
	fmt.Fprintf(&b, "- npm package: %s → %s", r.Old, r.New)
	if r.Nix {
		fmt.Fprintf(&b, "\n- flake.nix: %s → %s", r.Old, r.New)
	}
	fmt.Fprintf(&b, "\n\nGenerated by bump-version")
	return b.String()
}

// Tag makes the annotated tag vVERSION on the commit just made, with the script's
// release message.
func Tag(g Git, root, version string) error {
	return gitRun(g, root, "tag", "-a", "v"+version, "-m", "Release v"+version)
}

// NextSteps prints the lines the operator runs to publish the release. It prints
// them and never pushes: main lands only through the landing worker, and the tag is
// pushed by the release procedure. tagged reports whether the tag was made, which
// decides whether the operator still has to create it.
func NextSteps(out io.Writer, version string, tagged bool) {
	fmt.Fprintln(out, "Next steps:")
	fmt.Fprintln(out, "  git push origin main")
	if !tagged {
		fmt.Fprintf(out, "  git tag -a v%s -m 'Release v%s'\n", version, version)
	}
	fmt.Fprintf(out, "  git push origin v%s\n", version)
}

// gitRun runs one git step and reports a non-zero exit by its status alone. git's
// output is not in the error, since it can hold anything the commit or tag printed.
func gitRun(g Git, root string, args ...string) error {
	code, err := g.Run(root, args...)
	if err != nil {
		return fmt.Errorf("git %s: %w", args[0], err)
	}
	if code != 0 {
		return fmt.Errorf("git %s: exit %d", args[0], code)
	}
	return nil
}

// Installer is the seam for the install step. Exec runs make install in Root and
// the installed gt. Executable reports whether path is an executable file. Home is
// the user's home directory, under which make install puts gt in .local/bin.
type Installer struct {
	Exec       Exec
	Executable func(path string) bool
	Home       string
	Root       string
}

// semverInText is the first MAJOR.MINOR.PATCH in a gt version line, as the script's
// grep -oE takes it.
var semverInText = regexp.MustCompile(`[0-9]+\.[0-9]+\.[0-9]+`)

// Install runs make install in Root, then reads the version the installed gt reports
// and compares it with want. The gt it reads is $Home/.local/bin/gt when that is
// executable, else the gt on PATH, as the script does. A match prints Verified. A
// mismatch prints a warning with both versions and is not an error, since the
// install itself succeeded. A failed make install is an error whose text is fixed,
// so make's output never reaches the message.
func (in Installer) Install(want string, out io.Writer) error {
	if _, _, err := in.Exec.Run(in.Root, nil, "make", "install"); err != nil {
		return errors.New("make install failed")
	}
	fmt.Fprintln(out, "✓ gt installed")

	gt := "gt"
	if local := filepath.Join(in.Home, ".local", "bin", "gt"); in.Executable(local) {
		gt = local
	}
	// The exit status is not checked, as in the script: a gt that prints no version
	// leaves got empty, which is reported as a mismatch.
	stdout, stderr, _ := in.Exec.Run(in.Root, nil, gt, "version")
	got := semverInText.FindString(string(stdout) + string(stderr))
	if got == want {
		fmt.Fprintf(out, "✓ Verified: gt version %s\n", got)
		return nil
	}
	fmt.Fprintf(out, "⚠ gt reports %s (expected %s)\n", got, want)
	return nil
}
