// TestNextStepsPrintsButNeverPushes: the next-step lines match the script for a
// tagged and an untagged release, and print the push and the tag as text only.
func TestNextStepsPrintsButNeverPushes(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		tagged bool
		want   string
	}{
		{
			name:   "tagged",
			tagged: true,
			want:   "Next steps:\n  git push origin main\n  git push origin v0.2.0\n",
		},
		{
			name:   "untagged",
			tagged: false,
			want: "Next steps:\n  git push origin main\n" +
				"  git tag -a v0.2.0 -m 'Release v0.2.0'\n  git push origin v0.2.0\n",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			var out bytes.Buffer
			NextSteps(&out, "0.2.0", tc.tagged)
			if out.String() != tc.want {
				t.Errorf("NextSteps wrote %q, want %q", out.String(), tc.want)
			}
		})
	}
}

// TestNeverPushes: across every flag combination the command can take, and both
// tree states, no git call is a push. The steps run as the command runs them, with
// the commit guarded by --commit and the tag by --tag.
func TestNeverPushes(t *testing.T) {
	t.Parallel()
	bools := []bool{false, true}
	for _, commit := range bools {
		for _, tag := range bools {
			for _, allowDirty := range bools {
				for _, nix := range bools {
					for _, hasFlake := range bools {
						for _, hasLog := range bools {
							for _, dirty := range bools {
								opts := Options{Commit: commit, Tag: tag, AllowDirty: allowDirty}
								f := &fakeGit{codes: map[string]int{}}
								if dirty {
									f.codes["diff-index"] = dirtyExit
								}
								files := map[string]string{}
								if hasFlake {
									files[FlakePath] = "x"
								}
								if hasLog {
									files[ChangelogPath] = "x"
								}
								var out bytes.Buffer
								if err := CheckTree(f.git(), "/root", opts, &out); err == nil && opts.Commit {
									if err := Commit(f.git(), &memFS{files: files}, "/root", releaseFor(nix)); err != nil {
										t.Fatalf("Commit(%+v): %v", opts, err)
									}
									if opts.Tag {
										if err := Tag(f.git(), "/root", "0.2.0"); err != nil {
											t.Fatalf("Tag(%+v): %v", opts, err)
										}
									}
								}
								NextSteps(&out, "0.2.0", opts.Tag)
								for _, sub := range f.subcommands() {
									if sub == "push" {
										t.Errorf("options %+v dirty=%v nix=%v flake=%v log=%v: git push was run", opts, dirty, nix, hasFlake, hasLog)
									}
								}
							}
						}
					}
				}
			}
		}
	}
}

// TestDirtyTreeRules: a clean tree passes. A dirty tree is refused under --commit,
// even with --allow-dirty, and without --commit is refused unless --allow-dirty is
// given. A git that fails for any other reason is an error, never a clean tree.
func TestDirtyTreeRules(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name        string
		git         fakeGit
		opts        Options
		wantErr     string // substring of the error; "" for no error
		wantRefusal bool
		wantWarning bool
	}{
		{name: "clean", git: fakeGit{codes: map[string]int{"diff-index": 0}}, opts: Options{}},
		{name: "clean under commit", git: fakeGit{codes: map[string]int{"diff-index": 0}}, opts: Options{Commit: true}},
		{
			name:        "dirty without flags is refused",
			git:         fakeGit{codes: map[string]int{"diff-index": dirtyExit}},
			opts:        Options{},
			wantErr:     "--allow-dirty",
			wantRefusal: true,
			wantWarning: true,
		},
		{
			name:        "dirty with allow-dirty continues",
			git:         fakeGit{codes: map[string]int{"diff-index": dirtyExit}},
			opts:        Options{AllowDirty: true},
			wantWarning: true,
		},
		{
			name:        "dirty under commit is refused",
			git:         fakeGit{codes: map[string]int{"diff-index": dirtyExit}},
			opts:        Options{Commit: true},
			wantErr:     "Cannot auto-commit",
			wantRefusal: true,
			wantWarning: true,
		},
		{
			name:        "dirty under commit stays refused with allow-dirty",
			git:         fakeGit{codes: map[string]int{"diff-index": dirtyExit}},
			opts:        Options{Commit: true, AllowDirty: true},
			wantErr:     "Cannot auto-commit",
			wantRefusal: true,
			wantWarning: true,
		},
		{
			name:    "git status other than dirty is an error, not clean",
			git:     fakeGit{codes: map[string]int{"diff-index": 128}},
			opts:    Options{AllowDirty: true},
			wantErr: "git diff-index: exit 128",
		},
		{
			name:    "git cannot start is an error",
			git:     fakeGit{startErr: errors.New("exec: git not found")},
			opts:    Options{AllowDirty: true},
			wantErr: "git diff-index: exec: git not found",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			f := tc.git
			var out bytes.Buffer
			err := CheckTree(f.git(), "/root", tc.opts, &out)
			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("CheckTree returned %v, want nil", err)
				}
			} else if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("CheckTree error = %v, want it to contain %q", err, tc.wantErr)
			}
			var refusal *Refusal
			if got := errors.As(err, &refusal); got != tc.wantRefusal {
				t.Errorf("CheckTree error is a Refusal = %v, want %v", got, tc.wantRefusal)
			}
			if got := strings.Contains(out.String(), "Warning: You have uncommitted changes"); got != tc.wantWarning {
				t.Errorf("CheckTree wrote the dirty warning = %v, want %v (output %q)", got, tc.wantWarning, out.String())
			}
		})
	}
}

// fakeRun is the process seam for the install step. makeErr is what make install
// returns, and gtOut is what the installed gt prints for its version line.
type fakeRun struct {
	makeErr error
	gtOut   string
	calls   []fakeCall
}

func (f *fakeRun) exec() Exec {
	return Exec{Run: func(dir string, env []string, name string, args ...string) ([]byte, []byte, error) {
		f.calls = append(f.calls, fakeCall{dir: dir, env: env, name: name, args: args})
		if name == "make" {
			return nil, nil, f.makeErr
		}
		return []byte(f.gtOut), nil, nil
	}}
}

// TestInstallVerifiesTheInstalledVersion: the version read is the one the installed
// gt reports. It is $HOME/.local/bin/gt when that is executable, else the gt on PATH.
// A match verifies, a mismatch warns with both versions, and a failed make install is
// an error whose text is fixed. Home and Executable are fakes, so no real binary is
// consulted.
func TestInstallVerifiesTheInstalledVersion(t *testing.T) {
	t.Parallel()
	const home = "/fake/home"
	local := filepath.Join(home, ".local", "bin", "gt")
	tests := []struct {
		name       string
		run        fakeRun
		executable bool
		wantGt     string
		wantOut    string
		wantErr    string
	}{
		{
			name:    "match via PATH",
			run:     fakeRun{gtOut: "gt version 0.2.0 (abc1234)\n"},
			wantGt:  "gt",
			wantOut: "✓ gt installed\n✓ Verified: gt version 0.2.0\n",
		},
		{
			name:       "match via the local install",
			run:        fakeRun{gtOut: "gt version 0.2.0\n"},
			executable: true,
			wantGt:     local,
			wantOut:    "✓ gt installed\n✓ Verified: gt version 0.2.0\n",
		},
		{
			name:    "mismatch warns with both versions",
			run:     fakeRun{gtOut: "gt version 0.1.0\n"},
			wantGt:  "gt",
			wantOut: "✓ gt installed\n⚠ gt reports 0.1.0 (expected 0.2.0)\n",
		},
		{
			name:    "no version line warns with an empty version",
			run:     fakeRun{gtOut: "boom\n"},
			wantGt:  "gt",
			wantOut: "✓ gt installed\n⚠ gt reports  (expected 0.2.0)\n",
		},
		{
			name:    "make install failure is an error with fixed text",
			run:     fakeRun{makeErr: errors.New("secret build output xyz")},
			wantErr: "make install failed",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			run := tc.run
			var probed []string
			in := Installer{
				Exec: run.exec(),
				Executable: func(path string) bool {
					probed = append(probed, path)
					return tc.executable && path == local
				},
				Home: home,
				Root: "/fake/root",
			}
			var out bytes.Buffer
			err := in.Install("0.2.0", &out)
			if tc.wantErr != "" {
				if err == nil || err.Error() != tc.wantErr {
					t.Fatalf("Install error = %v, want exactly %q", err, tc.wantErr)
				}
				if len(run.calls) != 1 || run.calls[0].name != "make" {
					t.Errorf("Install ran %v after make failed, want make alone", run.calls)
				}
				return
			}
			if err != nil {
				t.Fatalf("Install: %v", err)
			}
			if out.String() != tc.wantOut {
				t.Errorf("Install wrote %q, want %q", out.String(), tc.wantOut)
			}
			if len(run.calls) < 2 || run.calls[0].name != "make" || !reflect.DeepEqual(run.calls[0].args, []string{"install"}) {
				t.Fatalf("first call = %+v, want make install", run.calls)
			}
			if run.calls[0].dir != "/fake/root" {
				t.Errorf("make ran in %q, want /fake/root", run.calls[0].dir)
			}
			gt := run.calls[len(run.calls)-1]
			if gt.name != tc.wantGt || !reflect.DeepEqual(gt.args, []string{"version"}) {
				t.Errorf("version read ran %q %q, want %q version", gt.name, gt.args, tc.wantGt)
			}
			for _, p := range probed {
				if p != local {
					t.Errorf("probed %q, want only the local install %q", p, local)
				}
			}
		})
	}
}
