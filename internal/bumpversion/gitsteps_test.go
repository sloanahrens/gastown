// gitCall is one git command the fake git seam was asked to run.
type gitCall struct {
	dir  string
	args []string
}

// fakeGit is the git seam with scripted exit statuses. codes gives the status of
// each subcommand by its first argument, and 0 for any other. startErr makes every
// call fail to start, as when git is not installed.
type fakeGit struct {
	codes    map[string]int
	startErr error
	calls    []gitCall
}

func (f *fakeGit) git() Git {
	return Git{Run: func(dir string, args ...string) (int, error) {
		f.calls = append(f.calls, gitCall{dir: dir, args: args})
		if f.startErr != nil {
			return 0, f.startErr
		}
		return f.codes[args[0]], nil
	}}
}

// subcommands returns the first argument of each recorded call, in order.
func (f *fakeGit) subcommands() []string {
	var subs []string
	for _, c := range f.calls {
		subs = append(subs, c.args[0])
	}
	return subs
}

// callWith returns the args of the first recorded call whose subcommand is sub, or
// nil when there is none.
func (f *fakeGit) callWith(sub string) []string {
	for _, c := range f.calls {
		if c.args[0] == sub {
			return c.args
		}
	}
	return nil
}

// releaseFor is the release every commit test records: 0.1.0 to 0.2.0.
func releaseFor(nix bool) Release {
	return Release{Old: "0.1.0", New: "0.2.0", Nix: nix}
}

// TestCommitMessageGolden: the commit message is the script's, with the flake.nix
// line only when nix is on PATH, and it ends with the generated-by line.
func TestCommitMessageGolden(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		nix  bool
		want string
	}{
		{
			name: "without nix",
			nix:  false,
			want: "chore: Bump version to 0.2.0\n\n" +
				"Updated all component versions:\n" +
				"- gt CLI: 0.1.0 → 0.2.0\n" +
				"- npm package: 0.1.0 → 0.2.0\n\n" +
				"Generated by bump-version",
		},
		{
			name: "with nix",
			nix:  true,
			want: "chore: Bump version to 0.2.0\n\n" +
				"Updated all component versions:\n" +
				"- gt CLI: 0.1.0 → 0.2.0\n" +
				"- npm package: 0.1.0 → 0.2.0\n" +
				"- flake.nix: 0.1.0 → 0.2.0\n\n" +
				"Generated by bump-version",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			f := &fakeGit{}
			fsys := &memFS{files: map[string]string{FlakePath: "x"}}
			if err := Commit(f.git(), fsys, "/root", releaseFor(tc.nix)); err != nil {
				t.Fatalf("Commit: %v", err)
			}
			got := f.callWith("commit")
			if !reflect.DeepEqual(got, []string{"commit", "-m", tc.want}) {
				t.Errorf("commit args = %q, want the message %q", got, tc.want)
			}
		})
	}
}

// TestCommitAddsOnlyThePresentFiles: the version files are always staged, flake.nix
// only under nix and only when it exists, and CHANGELOG.md only when it exists. The
// mutation to guard is an unconditional flake.nix add.
func TestCommitAddsOnlyThePresentFiles(t *testing.T) {
	t.Parallel()
	base := []string{"add", VersionGoPath, PackageJSONPath}
	tests := []struct {
		name      string
		nix       bool
		hasFlake  bool
		hasLog    bool
		wantAdded []string
	}{
		{name: "no nix, no changelog", nix: false, hasFlake: false, hasLog: false, wantAdded: base},
		{name: "no nix, flake present is not staged", nix: false, hasFlake: true, hasLog: false, wantAdded: base},
		{name: "no nix, changelog present", nix: false, hasFlake: false, hasLog: true, wantAdded: append(append([]string{}, base...), ChangelogPath)},
		{name: "nix, flake present", nix: true, hasFlake: true, hasLog: false, wantAdded: append(append([]string{}, base...), FlakePath)},
		{name: "nix, flake absent", nix: true, hasFlake: false, hasLog: false, wantAdded: base},
		{name: "nix, both present", nix: true, hasFlake: true, hasLog: true, wantAdded: append(append([]string{}, base...), FlakePath, ChangelogPath)},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{}
			if tc.hasFlake {
				files[FlakePath] = "x"
			}
			if tc.hasLog {
				files[ChangelogPath] = "x"
			}
			f := &fakeGit{}
			if err := Commit(f.git(), &memFS{files: files}, "/root", releaseFor(tc.nix)); err != nil {
				t.Fatalf("Commit: %v", err)
			}
			if got := f.callWith("add"); !reflect.DeepEqual(got, tc.wantAdded) {
				t.Errorf("git add = %q, want %q", got, tc.wantAdded)
			}
			if got := f.subcommands(); !reflect.DeepEqual(got, []string{"add", "commit"}) {
				t.Errorf("git subcommands = %q, want add then commit", got)
			}
		})
	}
}

// TestCommitRunsInTheRoot: git runs in the repository root the caller names.
func TestCommitRunsInTheRoot(t *testing.T) {
	t.Parallel()
	f := &fakeGit{}
	if err := Commit(f.git(), &memFS{files: map[string]string{}}, "/sandbox/root", releaseFor(false)); err != nil {
		t.Fatalf("Commit: %v", err)
	}
	for _, c := range f.calls {
		if c.dir != "/sandbox/root" {
			t.Errorf("git %s ran in %q, want /sandbox/root", c.args[0], c.dir)
		}
	}
}

// TestCommitFailuresRefuse: each refusal stops the step before the next git command,
// names the git subcommand that failed, and never carries git's output.
func TestCommitFailuresRefuse(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		fsys     FS
		git      fakeGit
		nix      bool
		wantErr  string
		wantRuns []string
	}{
		{
			name:     "flake.nix unreadable under nix",
			fsys:     readErrFS{err: errors.New("disk on fire")},
			nix:      true,
			wantErr:  "read " + FlakePath,
			wantRuns: nil,
		},
		{
			name:     "git add exits non-zero",
			fsys:     &memFS{files: map[string]string{}},
			git:      fakeGit{codes: map[string]int{"add": 128}},
			wantErr:  "git add: exit 128",
			wantRuns: []string{"add"},
		},
		{
			name:     "git commit exits non-zero",
			fsys:     &memFS{files: map[string]string{}},
			git:      fakeGit{codes: map[string]int{"commit": 1}},
			wantErr:  "git commit: exit 1",
			wantRuns: []string{"add", "commit"},
		},
		{
			name:     "git cannot start",
			fsys:     &memFS{files: map[string]string{}},
			git:      fakeGit{startErr: errors.New("exec: git not found")},
			wantErr:  "git add: exec: git not found",
			wantRuns: []string{"add"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			f := tc.git
			err := Commit(f.git(), tc.fsys, "/root", releaseFor(tc.nix))
			if err == nil {
				t.Fatalf("Commit returned nil, want an error containing %q", tc.wantErr)
			}
			if !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("Commit error = %q, want it to contain %q", err, tc.wantErr)
			}
			if got := f.subcommands(); !reflect.DeepEqual(got, tc.wantRuns) {
				t.Errorf("git ran %q, want %q", got, tc.wantRuns)
			}
		})
	}
}

