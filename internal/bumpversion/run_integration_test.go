//go:build integration

package bumpversion

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// TestIntegrationRunCommitsAndTagsTheRepository drives Run through the real file and git
// seams over a throwaway repository. The run starts from a directory that is not the
// repository, so every file must be found through the root. make and gt are faked at the
// process seam and nix is absent. The three version files are edited, the commit and tag
// are made, and no git push is run.
func TestIntegrationRunCommitsAndTagsTheRepository(t *testing.T) {
	root := t.TempDir()
	t.Chdir(t.TempDir())
	gitEnv := isolatedGitEnv(t)
	git := realGit(gitEnv)

	gitOut(t, gitEnv, root, "init", "-q")
	files := map[string]string{
		VersionGoPath:   "package cmd\n\nvar (\n\tVersion = \"1.2.1\"\n)\n",
		PackageJSONPath: "{\n  \"version\": \"1.2.1\"\n}\n",
		ChangelogPath:   "# Changelog\n\n## [Unreleased]\n\n- Initial work.\n",
	}
	for name, text := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	gitOut(t, gitEnv, root, "add", "-A")
	gitOut(t, gitEnv, root, "commit", "-q", "-m", "fixture")

	var out bytes.Buffer
	var makes int
	env := Env{
		FS:         diskFS{root: root},
		Root:       root,
		Home:       t.TempDir(),
		Date:       "2026-10-30",
		Executable: func(string) bool { return false },
		Out:        &out,
	}
	env.Git = Git{Run: func(dir string, args ...string) (int, error) {
		if args[0] == "push" {
			t.Errorf("the run ran git %s; the command never pushes", strings.Join(args, " "))
		}
		return git.Run(dir, args...)
	}}
	env.Exec = Exec{
		Run: func(dir string, _ []string, name string, args ...string) ([]byte, []byte, error) {
			switch name {
			case "make":
				makes++
				return nil, nil, nil
			case "gt":
				return []byte("gt version 1.3.0\n"), nil, nil
			}
			// git diff --stat is the one other process the run starts. It runs in the
			// isolated environment, so the host's git configuration does not reach it.
			cmd := exec.Command(name, args...)
			cmd.Dir = dir
			cmd.Env = gitEnv
			stdout, err := cmd.Output()
			return stdout, nil, err
		},
		LookPath: func(file string) (string, error) {
			if file == "nix" {
				return "", exec.ErrNotFound
			}
			return exec.LookPath(file)
		},
		MkdirTemp: os.MkdirTemp,
	}

	if err := Run(env, Options{Version: "1.3.0", Commit: true, Tag: true, Install: true}); err != nil {
		t.Fatalf("Run: %v\n%s", err, out.String())
	}

	if makes != 1 {
		t.Errorf("make install ran %d times, want 1", makes)
	}
	if !strings.Contains(out.String(), "✓ Verified: gt version 1.3.0") {
		t.Errorf("output lacks the verified install line:\n%s", out.String())
	}
	if !strings.HasSuffix(out.String(), "Summary:\nCommitted and tagged v1.3.0.\n") {
		t.Errorf("output does not end with the summary:\n%s", out.String())
	}

	edits := map[string]string{
		VersionGoPath:   `Version = "1.3.0"`,
		PackageJSONPath: `"version": "1.3.0"`,
		ChangelogPath:   "## [1.3.0] - 2026-10-30",
	}
	for name, want := range edits {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), want) {
			t.Errorf("%s after the run lacks %q:\n%s", name, want, data)
		}
	}

	wantMessage := "chore: Bump version to 1.3.0\n\n" +
		"Updated all component versions:\n" +
		"- gt CLI: 1.2.1 → 1.3.0\n" +
		"- npm package: 1.2.1 → 1.3.0\n\n" +
		"Generated by bump-version"
	if got := gitOut(t, gitEnv, root, "log", "-1", "--format=%B"); got != wantMessage {
		t.Errorf("commit message = %q, want %q", got, wantMessage)
	}
	wantFiles := "CHANGELOG.md\ninternal/cmd/version.go\nnpm-package/package.json"
	if got := gitOut(t, gitEnv, root, "show", "--name-only", "--format=", "HEAD"); got != wantFiles {
		t.Errorf("files in the commit = %q, want %q", got, wantFiles)
	}
	if got := gitOut(t, gitEnv, root, "cat-file", "-t", "v1.3.0"); got != "tag" {
		t.Errorf("tag object type = %q, want an annotated tag object", got)
	}
	if got := gitOut(t, gitEnv, root, "status", "--porcelain"); got != "" {
		t.Errorf("working tree after the commit = %q, want clean", got)
	}
	if got := gitOut(t, gitEnv, root, "remote"); got != "" {
		t.Errorf("git remote = %q, want no remote to push to", got)
	}
}
